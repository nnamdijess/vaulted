  await friend.getByRole('button', { name: 'Pause playback', exact: true }).click();
  await friend.getByRole('button', { name: 'Resume playback', exact: true }).click();
  await expect.poll(async () => (await (await request.get(`${api}/projects/${project.id}/insights`)).json()).total).toBe(1);
  await friend.getByRole('button', { name: 'Pause playback', exact: true }).click();
  await friend.getByRole('button', { name: 'Resume playback', exact: true }).click();
  await expect.poll(() => friend.getByTestId('global-audio').evaluate((audio: HTMLAudioElement) => audio.ended)).toBe(true);
  expect((await (await request.get(`${api}/projects/${project.id}/insights`)).json()).total).toBe(1);
  await page.getByLabel('Allow downloads', { exact: true }).check();
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await friend.reload();
  await expect(friend.getByRole('link', { name: 'Download Listen once' })).toBeVisible();
  await friend.getByLabel('Theme', { exact: true }).selectOption('light');
  await friend.screenshot({ path: test.info().outputPath('shared-light.png'), fullPage: true });
