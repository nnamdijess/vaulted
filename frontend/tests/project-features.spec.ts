test('SSR controls and system/light/dark themes hydrate deterministically and persist', async ({ page, request }) => {
  const errors: string[] = [];
  const runtimeErrors: string[] = [];
  page.on('pageerror', (error) => runtimeErrors.push(error.message));
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
  const html = await (await request.get('http://127.0.0.1:3011/')).text();
  expect(html).toMatch(/aria-label="Previous track" disabled=""/);
  expect(html).toMatch(/aria-label="Next track" disabled=""/);
  await page.emulateMedia({ colorScheme: 'light' });
  await page.goto('/');
  await expect(page.locator('.theme-scope')).toHaveAttribute('data-theme', 'system');
  await expect(page.locator('.theme-scope')).toHaveCSS('background-color', 'rgb(247, 248, 244)');
  await expect(page.getByRole('button', { name: 'Previous track' })).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Next track' })).toBeDisabled();
  await page.getByLabel('Theme', { exact: true }).selectOption('dark');
  await expect(page.locator('.theme-scope')).toHaveCSS('background-color', 'rgb(16, 17, 19)');
  await page.reload();
  await expect(page.getByLabel('Theme', { exact: true })).toHaveValue('dark');
  await page.getByLabel('Theme', { exact: true }).selectOption('light');
  await page.reload();
  await expect(page.getByLabel('Theme', { exact: true })).toHaveValue('light');
  await expect(page.locator('.theme-scope')).toHaveCSS('background-color', 'rgb(247, 248, 244)');
  await page.getByLabel('Theme', { exact: true }).selectOption('system');
  await page.emulateMedia({ colorScheme: 'dark' });
  await expect(page.locator('.theme-scope')).toHaveCSS('background-color', 'rgb(16, 17, 19)');
  expect(errors.filter((error) => /hydrat|didn't match|does not match|server rendered|runtime/i.test(error))).toEqual([]);
  expect(runtimeErrors).toEqual([]);
});
