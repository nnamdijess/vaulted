import {test,expect} from '@playwright/test';
import {randomUUID} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {readFileSync} from 'node:fs';
import path from 'node:path';
import {wav} from './fixtures';

const base='http://127.0.0.1:8011/api';
test('owner activates footage vault, invites a member, and removes access on mobile',async({browser,request,page},info)=>{
 test.setTimeout(90000);
 test.skip(!process.env.VIDEO_VAULT_ADMIN_EMAIL,'Run with a unique VIDEO_VAULT_ADMIN_EMAIL for the isolated test server.');
 const email=`member-${randomUUID()}@example.com`;
 expect((await request.post(`${base}/auth/register`,{data:{email:process.env.VIDEO_VAULT_ADMIN_EMAIL,password:'Test-only-password-42',display_name:'Vault owner'}})).status()).toBe(201);
 await page.context().addCookies((await request.storageState()).cookies);
 const python=path.resolve('../backend/.venv/Scripts/python.exe');
 const ffmpeg=execFileSync(python,['-c','import imageio_ffmpeg; print(imageio_ffmpeg.get_ffmpeg_exe())']).toString().trim();
 const file=info.outputPath('shared.mp4');
 execFileSync(ffmpeg,['-v','error','-f','lavfi','-i','color=blue:s=108x192:r=30:d=3','-c:v','libx264','-pix_fmt','yuv420p',file]);
 expect((await request.post(`${base}/studio/media/upload`,{multipart:{file:{name:'shared.mp4',mimeType:'video/mp4',buffer:readFileSync(file)}}})).status()).toBe(201);
 await page.setViewportSize({width:390,height:844});
 await page.goto('/studio/vault');
 await page.getByRole('button',{name:'Activate Video Vault'}).click();
 await expect(page.getByText('1 shared clips · Owner')).toBeVisible();
 await page.getByLabel('Friend’s email').fill(email);
 await page.getByRole('button',{name:'Create invitation',exact:true}).click();
 const invitation=page.getByLabel('Invitation link');
 await expect(invitation).toHaveValue(/\/studio\/vault#/);
 const link=await invitation.inputValue();
 const member=await browser.newContext({viewport:{width:390,height:844}});
 expect((await member.request.post(`${base}/auth/register`,{data:{email,password:'Test-only-password-42',display_name:'Test friend'}})).status()).toBe(201);
 const friend=await member.newPage();
 await friend.goto(link);
 await friend.getByRole('button',{name:'Accept invitation'}).click();
 await expect(friend.getByText('1 shared clips · Contributor')).toBeVisible();
 await expect(friend.getByRole('button',{name:'Create invitation'})).toHaveCount(0);
 const music=await(await member.request.post(`${base}/projects`,{data:{name:'Private song'}})).json();
 const [song]=await(await member.request.post(`${base}/projects/${music.id}/tracks`,{multipart:{files:{name:'song.wav',mimeType:'audio/wav',buffer:wav()}}})).json();
 const draft=await(await member.request.post(`${base}/studio/projects`,{data:{title:'Member video',song_version_id:song.latest_version_id}})).json();
 await friend.goto(`http://127.0.0.1:3011/studio/${draft.id}`);
 await friend.getByRole('button',{name:'4. Visuals',exact:true}).click();
 await friend.getByRole('button',{name:'Review Media',exact:true}).click();
 await expect(friend.getByRole('tab',{name:'Vault clips',exact:true})).toBeVisible();
 await expect(friend.locator('.studio-media-grid article')).toHaveCount(1);
 await expect(friend.getByRole('button',{name:/Delete uploaded clip/})).toHaveCount(0);
 await expect(friend.getByRole('button',{name:'Move to Folder',exact:true})).toHaveCount(0);
 await expect(friend.getByText('Uploaded by Vault owner · Shared')).toBeVisible();
 await page.reload();
 await page.getByRole('button',{name:'Remove Test friend',exact:true}).click();
 await page.getByRole('dialog').getByRole('button',{name:'Remove member',exact:true}).click();
 await expect(page.getByText('No members yet.')).toBeVisible();
 expect(await(await member.request.get(`${base}/studio/media/favorites`)).json()).toEqual([]);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await page.screenshot({path:info.outputPath('vault-mobile.png'),fullPage:true});
 await member.close();
});
