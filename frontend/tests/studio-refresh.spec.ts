import { expect } from '@playwright/test';
import { test, wav, png } from './fixtures';

test('artwork library keeps five projects, three exports and accessible all-item views',async({page},info)=>{
  await page.route('**/api/studio/projects',route=>route.fulfill({json:Array.from({length:7},(_,i)=>({id:i+1,title:i===0?'A longer project title that wraps neatly across the card':'Late night session '+(i+1),song_title:'Demo track',status:i%2?'draft':'completed',project_id:1,song_id:1,cover_path:i%2?null:'cover.png',jobs:[{id:i+1,status:'completed'}]}))}));
  await page.route('**/cover?*',route=>route.fulfill({contentType:'image/png',body:png}));
  await page.route('**/renders/*/poster',route=>route.fulfill({contentType:'image/png',body:png}));
  await page.setViewportSize({width:1440,height:1000});
  await page.emulateMedia({colorScheme:'dark'});
  await page.goto('/studio');
  const projects=page.getByRole('region',{name:'Recent Content Projects'});
  await expect(projects.locator('.studio-card')).toHaveCount(5);
  await expect(page.getByRole('region',{name:'Completed exports'}).locator('.studio-render-card')).toHaveCount(3);
  const cards=await projects.locator('.studio-card').all();
  const tops=await Promise.all(cards.map(async card=>(await card.boundingBox())!.y));
  expect(Math.max(...tops)-Math.min(...tops)).toBeLessThan(2);
  await page.screenshot({path:info.outputPath('studio-desktop-dark.png'),fullPage:true});
  await page.emulateMedia({colorScheme:'light'});
  await page.screenshot({path:info.outputPath('studio-desktop-light.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  const first=(await cards[0].boundingBox())!,second=(await cards[1].boundingBox())!;
  expect(first.y).toBeCloseTo(second.y,0);
  await page.screenshot({path:info.outputPath('studio-mobile-light.png'),fullPage:true});
  await projects.getByRole('button',{name:/View all projects/}).click();
  await expect(page.getByRole('dialog',{name:'All content projects'}).locator('.studio-card')).toHaveCount(7);
  await page.keyboard.press('Escape');
  await expect(projects.getByRole('button',{name:/View all projects/})).toBeFocused();
});

test('mobile inspector groups keep settings usable and font search preserves selection',async({page,request},info)=>{
  const base='http://127.0.0.1:8011/api';
  const music=await(await request.post(`${base}/projects`,{data:{name:'Design review'}})).json();
  const [song]=await(await request.post(`${base}/projects/${music.id}/tracks`,{multipart:{files:{name:'Evening.wav',mimeType:'audio/wav',buffer:wav()}}})).json();
  const draft=await(await request.post(`${base}/studio/projects`,{data:{song_version_id:song.latest_version_id,title:'Evening draft'}})).json();
  await page.setViewportSize({width:390,height:844});
  await page.emulateMedia({colorScheme:'dark',reducedMotion:'reduce'});
  await page.goto(`/studio/${draft.id}`);
  await page.getByRole('button',{name:'4. Visuals',exact:true}).click();
  await page.screenshot({path:info.outputPath('studio-editor-mobile.png')});
  const panel=page.getByRole('complementary',{name:'Text styling'});
  await expect(panel.getByRole('button',{name:'Anton',exact:true})).not.toBeVisible();
  await panel.getByTestId('studio-font-group').locator('summary').click();
  await panel.getByLabel('Find a font').fill('anton');
  await expect(panel.locator('.studio-font-options button')).toHaveCount(1);
  await panel.getByRole('button',{name:'Anton',exact:true}).click();
  await panel.getByLabel('Find a font').fill('no font like this');
  await expect(panel.getByText('No fonts match your search.')).toBeVisible();
  await panel.getByLabel('Find a font').fill('');
  await panel.getByTestId('studio-font-group').locator('summary').click();
  await expect(panel.getByTestId('studio-font-group').locator('summary')).toContainText('Anton');
  await panel.locator('summary').filter({hasText:'Size & spacing'}).click();
  await panel.getByLabel('Font Size',{exact:true}).fill('64');
  await expect(page.locator('.studio-autosave')).toHaveText('Saved');
  await panel.locator('summary').filter({hasText:'Size & spacing'}).click();
  await panel.scrollIntoViewIfNeeded();
  await page.screenshot({path:info.outputPath('studio-inspector-mobile.png')});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.reload();
  await page.getByRole('button',{name:'4. Visuals',exact:true}).click();
  await expect(panel.getByTestId('studio-font-group').locator('summary')).toContainText('Anton');
  await expect(panel.locator('summary').filter({hasText:'Size & spacing'})).toContainText('64px');
});
