import { expect } from '@playwright/test';
import { test, wav } from './fixtures';

test('Vaulted preferences persist, tracks drag into saved order, and mobile player stays compact', async ({ page, request, browser }, testInfo) => {
  await page.setViewportSize({ width: 1280, height: 1100 });
  const base = 'http://127.0.0.1:8011/api';
  const project = await (await request.post(`${base}/projects`, { data: { name: 'Reorder album' } })).json();
  const songs = [];
  for (const title of ['First','Second','Third']) {
    const uploaded = await (await request.post(`${base}/projects/${project.id}/tracks`, { multipart: { files: { name: `${title}.wav`, mimeType: 'audio/wav', buffer: wav() } } })).json();
    songs.push(uploaded[0]);
  }
  await page.goto('/profile');
  await expect(page).toHaveTitle('Vaulted');
  await page.getByLabel('Library name', { exact: true }).fill('Night sessions');
  await page.getByRole('combobox', { name: 'Accent color', exact: true }).selectOption('blue');
  await page.getByRole('button', { name: 'Save preferences' }).click();
  await expect(page.locator('.account-scope')).toHaveAttribute('data-accent','blue');
  await page.getByLabel('Theme', { exact: true }).selectOption('light');
  await expect(page.locator('.brand .dot')).toHaveCSS('color','rgb(18, 98, 181)');
  await page.reload();
  await expect(page.getByLabel('Library name', { exact: true })).toHaveValue('Night sessions');
  await expect(page.getByRole('combobox', { name: 'Accent color', exact: true })).toHaveValue('blue');
  await page.getByLabel('Theme', { exact: true }).selectOption('dark');
  await expect(page.locator('.brand .dot')).toHaveCSS('color','rgb(88, 173, 255)');
  await page.goto('/projects');
  await expect(page.getByRole('heading', { name: 'Night sessions' })).toBeVisible();
  await page.goto(`/projects/${project.id}`);
  await page.getByRole('button', { name: 'Project actions', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Sort tracks', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Close project actions' }).click();
  const order = () => page.locator('[data-track-id]').evaluateAll(rows => rows.map(row => Number((row as HTMLElement).dataset.trackId)));
  const from = (await page.getByRole('button', { name: 'Reorder Third', exact: true }).boundingBox())!;
  const to = (await page.getByRole('button', { name: 'Reorder First', exact: true }).boundingBox())!;
  await page.mouse.move(from.x + from.width / 2, from.y + from.height / 2); await page.mouse.down();
  await page.mouse.move(to.x + to.width / 2, to.y + to.height / 2, { steps: 12 }); await page.mouse.up();
  await expect.poll(async () => (await (await request.get(`${base}/projects/${project.id}/songs`)).json()).map((song: { id: number }) => song.id)).toEqual([songs[2].id,songs[0].id,songs[1].id]);
  await page.reload();
  await expect.poll(order).toEqual([songs[2].id,songs[0].id,songs[1].id]);
  const handle = page.getByRole('button', { name: 'Reorder Third', exact: true });
  await handle.press('Space'); await handle.press('ArrowDown'); await handle.press('Escape');
  await expect.poll(order).toEqual([songs[2].id,songs[0].id,songs[1].id]);
  await page.getByRole('button', { name: 'Play All' }).click();
  await page.getByRole('button', { name: 'Pause playback', exact: true }).click();
  await handle.press('Space'); await handle.press('ArrowDown'); await handle.press('Enter');
  await expect.poll(async () => (await (await request.get(`${base}/projects/${project.id}/songs`)).json()).map((song: { id: number }) => song.id)).toEqual([songs[0].id,songs[2].id,songs[1].id]);
  await expect(page.getByRole('button', { name: 'Previous track' })).toBeEnabled();
  await expect(page.getByRole('button', { name: 'Next track' })).toBeEnabled();
  await expect(page.getByRole('complementary', { name: 'Audio player' })).toContainText('Third');
  const token = (await (await request.put(`${base}/projects/${project.id}/share`, { data: { enabled: true } })).json()).token;
  const publicView = await (await request.get(`${base}/public/${token}`)).json();
  expect(publicView.tracks.map((song: { id: number }) => song.id)).toEqual([songs[0].id,songs[2].id,songs[1].id]);
  const context = await browser.newContext({ viewport: { width: 393, height: 852 }, isMobile: true, hasTouch: true });
  await context.addCookies((await request.storageState()).cookies);
  const mobile = await context.newPage(); await mobile.goto(`/projects/${project.id}`);
  await mobile.getByRole('button', { name: 'Reorder Third', exact: true }).scrollIntoViewIfNeeded();
  const mobileFrom = (await mobile.getByRole('button', { name: 'Reorder Third', exact: true }).boundingBox())!;
  const mobileTo = (await mobile.getByRole('button', { name: 'Reorder First', exact: true }).boundingBox())!;
  const cdp = await context.newCDPSession(mobile);
  await cdp.send('Input.dispatchTouchEvent', { type:'touchStart', touchPoints:[{ x:mobileFrom.x+10,y:mobileFrom.y+20 }] });
  await cdp.send('Input.dispatchTouchEvent', { type:'touchMove', touchPoints:[{ x:mobileTo.x+10,y:mobileTo.y+20 }] });
  await cdp.send('Input.dispatchTouchEvent', { type:'touchEnd', touchPoints:[] });
  await expect.poll(async () => (await (await request.get(`${base}/projects/${project.id}/songs`)).json()).map((song: { id: number }) => song.id)).toEqual([songs[2].id,songs[0].id,songs[1].id]);
  await cdp.detach();
  await mobile.getByRole('button', { name: 'Play All' }).press('Enter');
  await expect(mobile.getByTestId('audio-waveform')).toBeVisible();
  const dock = mobile.getByRole('complementary', { name: 'Audio player' });
  expect((await dock.boundingBox())!.height).toBeLessThan(85);
  expect(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await mobile.screenshot({ path: testInfo.outputPath('vaulted-mobile.png') });
  await context.close();
});
