import { expect } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { test, wav } from './fixtures';

test('sequence displays playable clips, replacement and mobile layout', async ({ page, request }, testInfo) => {
  const python = path.resolve('../backend', process.platform === 'win32' ? '.venv/Scripts/python.exe' : '.venv/bin/python');
  const ffmpeg = execFileSync(python, ['-c', 'import imageio_ffmpeg; print(imageio_ffmpeg.get_ffmpeg_exe())']).toString().trim();
  const fixture = testInfo.outputPath('preview.mp4');
  execFileSync(ffmpeg, ['-v', 'error', '-f', 'lavfi', '-i', 'testsrc2=size=160x240:rate=10', '-t', '3', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-movflags', '+faststart', fixture]);
  const body = readFileSync(fixture);
  await page.route('**/test-preview.mp4*', route => route.fulfill({ contentType: 'video/mp4', body }));
  const music = await (await request.post('http://127.0.0.1:8011/api/projects', { data: { name: 'Video cards' } })).json();
  const songs = await (await request.post(`http://127.0.0.1:8011/api/projects/${music.id}/tracks`, { multipart: { files: { name: 'A.wav', mimeType: 'audio/wav', buffer: wav() } } })).json();
  const draft = await (await request.post('http://127.0.0.1:8011/api/studio/projects', { data: { title: 'Videos', song_version_id: songs[0].latest_version_id } })).json();
  const media = { id: 1, preview_url: '/test-preview.mp4', tags: 'Actual footage', duration: 3, source_url: 'https://pixabay.com/' };
  draft.clips = [0, 1].map(index => ({ id: index + 1, start_time: index, end_time: index + 1, source_start: 0, media }));
  await page.route(`**/api/studio/projects/${draft.id}`, route => route.fulfill({ json: draft }));
  await page.goto(`/studio/${draft.id}`);
  await page.getByRole('button', { name: '4. Visuals', exact: true }).click();
  const first = page.getByLabel('Preview sequence clip 1', { exact: true });
  const second = page.getByLabel('Preview sequence clip 2', { exact: true });
  await first.scrollIntoViewIfNeeded();
  await expect.poll(() => first.evaluate((video: HTMLVideoElement) => video.videoWidth)).toBe(160);
  await expect.poll(() => first.evaluate((video: HTMLVideoElement) => video.readyState)).toBeGreaterThanOrEqual(2);
  await first.evaluate((video: HTMLVideoElement) => video.play());
  await expect(first).toHaveJSProperty('paused', false);
  await second.evaluate((video: HTMLVideoElement) => video.play());
  await expect(first).toHaveJSProperty('paused', true);
  await expect(second).toHaveJSProperty('paused', true, { timeout: 4000 });
  await page.getByRole('button', { name: 'Replace Clip', exact: true }).first().click();
  await expect(page.getByRole('status')).toContainText('Choose a clip');
  await page.getByRole('button', { name: 'Cancel replacement' }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await first.scrollIntoViewIfNeeded();
  await expect(first).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('sequence-mobile.png') });
});
