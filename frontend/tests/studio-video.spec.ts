import { expect } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { test, wav } from './fixtures';

test('draft timeline plays across sections, seeks and replaces only the selected footage', async ({ page, request }, testInfo) => {
  const python = path.resolve('../backend', process.platform === 'win32' ? '.venv/Scripts/python.exe' : '.venv/bin/python');
  const ffmpeg = execFileSync(python, ['-c', 'import imageio_ffmpeg; print(imageio_ffmpeg.get_ffmpeg_exe())']).toString().trim();
  const fixture = testInfo.outputPath('preview.mp4');
  execFileSync(ffmpeg, ['-v', 'error', '-f', 'lavfi', '-i', 'testsrc2=size=160x240:rate=10', '-t', '6', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-movflags', '+faststart', fixture]);
  const body = readFileSync(fixture);
  await page.route('**/test-preview.mp4*', route => route.fulfill({ contentType: 'video/mp4', body }));
  const audio = Buffer.alloc(44 + 8000 * 12 * 2);
  wav().copy(audio, 0, 0, 44);
  audio.writeUInt32LE(audio.length - 8, 4); audio.writeUInt32LE(audio.length - 44, 40);
  const music = await (await request.post('http://127.0.0.1:8011/api/projects', { data: { name: 'Video cards' } })).json();
  const songs = await (await request.post(`http://127.0.0.1:8011/api/projects/${music.id}/tracks`, { multipart: { files: { name: 'A.wav', mimeType: 'audio/wav', buffer: audio } } })).json();
  const draft = await (await request.post('http://127.0.0.1:8011/api/studio/projects', { data: { title: 'Videos', song_version_id: songs[0].latest_version_id } })).json();
  const media = { id: 1, preview_url: '/test-preview.mp4', tags: 'Actual footage', duration: 6, source_url: 'https://pixabay.com/' };
  draft.end_time = 8;
  draft.lines = [{ text: 'First lyric', start_time: 0, end_time: 4 }, { text: 'Second lyric', start_time: 4, end_time: 8 }];
  draft.clips = [0, 1].map(index => ({ id: index + 1, start_time: index * 4, end_time: (index + 1) * 4, source_start: 0, media: { ...media, preview_url: `/test-preview.mp4?clip=${index}` } }));
  const replacement = { ...media, id: 2, provider: 'pexels', author: 'Test creator', source_url: 'https://www.pexels.com/video/12/', preview_url: '/test-preview.mp4?replacement', tags: 'Replacement footage' };
  await page.route('**/api/studio/visuals/search', route => {
    expect(route.request().postDataJSON().provider).toBe('pexels');
    return route.fulfill({ json: [replacement] });
  });
  await page.route(`**/api/studio/projects/${draft.id}/clips/2`, async route => {
    expect(route.request().method()).toBe('PUT');
    expect(route.request().postDataJSON()).toEqual({ media_id: 2 });
    draft.clips[1].media = replacement;
    await route.fulfill({ json: draft });
  });
  await page.route(`**/api/studio/projects/${draft.id}`, route => route.fulfill({ json: draft }));
  await page.goto(`/studio/${draft.id}`);
  await page.getByRole('button', { name: '4. Visuals', exact: true }).click();
  const preview = page.getByLabel('Draft preview', { exact: true });
  const section1 = page.getByRole('button', { name: /^Select section 1,/ });
  const section2 = page.getByRole('button', { name: /^Select section 2,/ });
  await expect(preview).toHaveCount(1);
  await expect(page.getByLabel('Search visuals')).toBeHidden();
  await expect.poll(() => preview.evaluate((video: HTMLVideoElement) => video.videoWidth)).toBe(160);
  await section2.click();
  await expect(section2).toHaveAttribute('aria-pressed', 'true');
  await expect(preview).toHaveAttribute('src', '/test-preview.mp4?clip=1');
  await expect(page.locator('.studio-draft-preview p')).toHaveText('Second lyric');
  const textPanel = page.getByRole('complementary', { name: 'Text styling' });
  await textPanel.getByRole('button', { name: 'Pink text' }).click();
  await textPanel.getByRole('button', { name: 'Abel', exact: true }).click();
  await textPanel.getByRole('button', { name: 'Align right' }).click();
  await expect(page.locator('.studio-draft-preview p')).toHaveCSS('color', 'rgb(255, 107, 174)');
  await expect(page.locator('.studio-draft-preview p')).toHaveCSS('text-align', 'right');
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.screenshot({ path: testInfo.outputPath('text-and-video-dark.png'), fullPage: true });
  await textPanel.getByRole('button', { name: 'Cancel style changes' }).click();
  await section1.click();
  await page.getByRole('button', { name: 'Play draft', exact: true }).click();
  await expect(preview).toHaveJSProperty('paused', false);
  await expect(section2).toHaveAttribute('aria-pressed', 'true', { timeout: 7000 });
  await expect(preview).toHaveAttribute('src', '/test-preview.mp4?clip=1');
  await page.getByRole('button', { name: 'Pause draft', exact: true }).click();
  await expect(preview).toHaveJSProperty('paused', true);
  const position = page.getByRole('slider', { name: 'Draft position' });
  await position.fill('2');
  await expect(section1).toHaveAttribute('aria-pressed', 'true');
  await position.focus(); await page.keyboard.press('ArrowRight');
  await expect(position).toHaveValue('2.01');
  await section2.click();
  await page.getByRole('button', { name: 'Replace selected clip' }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Choose footage' })).toContainText('section 2');
  await page.getByLabel('Footage source').selectOption('pexels');
  await page.getByRole('button', { name: 'Search footage', exact: true }).click();
  await expect(page.getByRole('link', { name: 'Video by Test creator on Pexels' })).toBeVisible();
  await page.getByRole('button', { name: 'Use replacement', exact: true }).click();
  await expect(preview).toHaveAttribute('src', replacement.preview_url);
  await expect(section2).toHaveAttribute('aria-label', 'Select section 2, 0:04.0 to 0:08.0');
  await section1.click();
  await expect(preview).toHaveAttribute('src', '/test-preview.mp4?clip=0');
  await page.reload();
  await page.getByRole('button', { name: '4. Visuals', exact: true }).click();
  await section2.click();
  await expect(preview).toHaveAttribute('src', replacement.preview_url);
  await page.getByRole('button', { name: 'Replace selected clip' }).click();
  await page.getByRole('button', { name: 'Cancel replacement' }).click();
  await expect(preview).toHaveAttribute('src', replacement.preview_url);
  await page.setViewportSize({ width: 390, height: 844 });
  await preview.scrollIntoViewIfNeeded();
  await expect(preview).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('timeline-mobile.png') });
  await page.getByRole('button', { name: 'Play draft', exact: true }).click();
  await page.getByRole('button', { name: '3. Sync', exact: true }).click();
  await expect(page.getByTestId('global-audio')).toHaveJSProperty('paused', true);
});
