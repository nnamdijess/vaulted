import { expect } from '@playwright/test';
import { test, wav } from './fixtures';

test('Studio mobile song, section, lyrics and private draft flow', async ({ page, request }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error' && /hydration|hydrated/i.test(message.text())) errors.push(message.text()); });
  await page.setViewportSize({ width: 390, height: 844 });
  const music = await (await request.post('http://127.0.0.1:8011/api/projects', { data: { name: 'Studio source' } })).json();
  const songs = await (await request.post(`http://127.0.0.1:8011/api/projects/${music.id}/tracks`, { multipart: { files: { name: 'Studio tune.wav', mimeType: 'audio/wav', buffer: wav() } } })).json();
  await page.goto('/studio');
  await expect(page.getByRole('heading', { name: 'Studio', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Create New' }).click();
  await page.getByRole('combobox', { name: 'Version', exact: true }).selectOption(String(songs[0].latest_version_id));
  await expect(page.getByRole('heading', { name: 'Studio tune', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '2. Lyrics & look', exact: true }).click();
  await page.getByLabel('Lyrics', { exact: true }).fill('First line\nSecond line');
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  await page.getByRole('button', { name: '3. Sync', exact: true }).click();
  await page.getByLabel('Line 1 start', { exact: true }).fill('0');
  await page.getByLabel('Line 2 start', { exact: true }).fill('1.2');
  await page.getByRole('button', { name: 'Save timing' }).click();
  await expect(page.getByRole('status')).toContainText('Timing saved');
  await page.getByRole('button', { name: 'Preview synced lyrics', exact: true }).click();
  await expect(page.getByTestId('global-audio')).toHaveJSProperty('paused', false);
  await expect(page.getByTestId('global-audio')).toHaveJSProperty('paused', true, { timeout: 6000 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.reload();
  await page.getByRole('button', { name: '3. Sync', exact: true }).click();
  await expect(page.getByLabel('Line 2 start', { exact: true })).toHaveValue('1.2');
  await page.getByRole('button', { name: '4. Visuals', exact: true }).click();
  await page.getByRole('button', { name: 'Review Media', exact: true }).click();
  await expect(page.getByRole('alert').filter({ hasText: 'PIXABAY_API_KEY' })).toBeVisible();
  expect(errors).toEqual([]);
  const endpoint = page.url().match(/\/studio\/(\d+)/)![1];
  const anonymous = await page.context().browser()!.newContext();
  expect((await anonymous.request.get(`http://127.0.0.1:3011/api/studio/projects/${endpoint}`)).status()).toBe(401);
  await anonymous.close();
  const insights = await (await request.get(`http://127.0.0.1:8011/api/projects/${music.id}/insights`)).json();
  expect(insights.total).toBe(0);
  await page.getByRole('button', { name: '1. Section', exact: true }).click();
  const inactiveStep = page.getByRole('button', { name: '2. Lyrics & look', exact: true });
  expect(await inactiveStep.evaluate(element => getComputedStyle(element).color)).not.toBe(await page.locator('.theme-scope').evaluate(element => getComputedStyle(element).backgroundColor));
  await page.screenshot({ path: 'test-results/studio-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1280, height: 900 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/studio-desktop.png', fullPage: true });
});
