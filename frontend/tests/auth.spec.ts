import { expect, test } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { wav } from './fixtures';

const password = 'Browser-test-password-42';

test('register, login errors, logout, protected routes and account isolation', async ({ page, request }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (/hydration|did not match/i.test(message.text())) errors.push(message.text()); });
  const email = `browser-${randomUUID()}@example.com`;
  await page.goto('/projects');
  await expect(page).toHaveURL(/\/login/);
  await page.goto('/register');
  await page.getByLabel('Display name').fill('Account A');
  await page.getByLabel('Email').fill(email);
  await page.getByLabel('Password').fill(password);
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await expect(page).toHaveURL(/\/projects$/);
  await expect(page.getByText('Account A', { exact: true })).toBeVisible();
  const projectResponse = await page.request.post('/api/projects', { data: { name: 'A private album' } });
  expect(projectResponse.status()).toBe(201);
  const project = await projectResponse.json();
  const uploaded = await page.request.post(`/api/projects/${project.id}/tracks`, { multipart: { files: { name: 'Private track.wav', mimeType: 'audio/wav', buffer: wav() } } });
  expect(uploaded.status()).toBe(201);
  const songs = await uploaded.json();
  const token = (await (await page.request.put(`/api/projects/${project.id}/share`, { data: { enabled: true } })).json()).token;
  await page.goto(`/projects/${project.id}`);
  await page.getByRole('button', { name: 'Play All' }).click();
  const cookie = (await page.context().cookies()).find(item => item.name === 'unreleased_session');
  expect(cookie?.httpOnly).toBe(true);
  expect(cookie?.sameSite).toBe('Lax');
  await page.getByRole('button', { name: 'Log out', exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  await expect(page.getByRole('complementary', { name: 'Audio player' })).not.toContainText('Private track');
  expect((await request.get('/api/auth/me', { headers: { Cookie: `unreleased_session=${cookie?.value}` } })).status()).toBe(401);
  expect((await page.request.get(`/api/versions/${songs[0].latest_version_id}/audio`)).status()).toBe(401);
  await page.goto(`/share/${token}`);
  await expect(page.getByRole('heading', { name: 'A private album' })).toBeVisible();
  await page.getByRole('button', { name: 'Play All' }).click();
  await expect.poll(() => page.getByTestId('global-audio').evaluate((audio: HTMLAudioElement) => audio.currentTime)).toBeGreaterThan(0);
  await page.goto('/login');
  await page.getByLabel('Email').fill(email);
  await page.getByLabel('Password').fill('Incorrect-password-42');
  await page.getByRole('button', { name: 'Log in', exact: true }).click();
  await expect(page.locator('main').getByRole('alert')).toContainText('Email or password is incorrect');
  await page.getByLabel('Password').fill(password);
  await page.getByRole('button', { name: 'Log in', exact: true }).click();
  await expect(page).toHaveURL(/\/projects$/);
  await expect(page.getByRole('heading', { name: 'A private album' })).toBeVisible();
  await page.reload();
  await expect(page.getByText('Account A', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Log out', exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  await page.goto('/register');
  await page.getByLabel('Display name').fill('Account B');
  await page.getByLabel('Email').fill(`second-${randomUUID()}@example.com`);
  await page.getByLabel('Password').fill(password);
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await expect(page).toHaveURL(/\/projects$/);
  await expect(page.getByText('Account B', { exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'A private album' })).toHaveCount(0);
  await page.goto(`/projects/${project.id}`);
  await expect(page.locator('main').getByRole('alert')).toContainText('Project not found');
  expect(await page.evaluate(() => Object.keys(localStorage).filter(key => /auth|token|session/i.test(key)))).toEqual([]);
  expect(errors).toEqual([]);
});
