import { expect } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { test, wav } from './fixtures';
const base = 'http://127.0.0.1:8011/api';

test('queued timeline and font autosaves retain newer edits; visual insertion, Space and retry work', async ({ page, request }, testInfo) => {
  const python = path.resolve('../backend', process.platform === 'win32' ? '.venv/Scripts/python.exe' : '.venv/bin/python');
  const ffmpeg = execFileSync(python, ['-c', 'import imageio_ffmpeg; print(imageio_ffmpeg.get_ffmpeg_exe())']).toString().trim();
  const fixture = testInfo.outputPath('generic.mp4');
  execFileSync(ffmpeg, ['-v', 'error', '-f', 'lavfi', '-i', 'testsrc2=size=160x240:rate=10', '-t', '6', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', fixture]);
  const uploaded = await request.post(`${base}/studio/media/upload`, { multipart: { file: { name: 'generic.mp4', mimeType: 'video/mp4', buffer: readFileSync(fixture) } } });
  expect(uploaded.status()).toBe(201);
  const media = await uploaded.json();
  const music = await (await request.post(`${base}/projects`, { data: { name: 'Autosave' } })).json();
  const [song] = await (await request.post(`${base}/projects/${music.id}/tracks`, { multipart: { files: { name: 'Demo.wav', mimeType: 'audio/wav', buffer: wav() } } })).json();
  const draft = await (await request.post(`${base}/studio/projects`, { data: { title: 'Autosave', song_version_id: song.latest_version_id } })).json();
  await request.put(`${base}/studio/projects/${draft.id}/timeline`, { data: { revision: draft.revision, clips: [1.5, 1.5].map(duration => ({ media_id: media.id, duration, source_start: 0 })) } });
  let release!: () => void;
  const gate = new Promise<void>(resolve => { release = resolve; });
  let started!: () => void;
  const firstStarted = new Promise<void>(resolve => { started = resolve; });
  let count = 0;
  await page.route(`**/api/studio/projects/${draft.id}/editor`, async route => {
    if (++count === 1) { started(); await gate; }
    const response = await route.fetch(); await route.fulfill({ response });
  });
  await page.goto(`/studio/${draft.id}`);
  await page.getByRole('button', { name: '4. Visuals', exact: true }).click();
  await page.getByRole('button', { name: 'Pink text' }).click();
  await firstStarted;
  await page.getByRole('button', { name: 'Blue text' }).click();
  await page.getByText('Clip options', { exact: true }).click();
  await page.getByRole('group', { name: 'Draft timeline' }).evaluate(el => el.scrollIntoView({ block: 'center' }));
  const edge = (await page.getByRole('button', { name: 'Trim end section 1' }).boundingBox())!;
  await page.mouse.move(edge.x + edge.width / 2, edge.y + edge.height / 2);
  await page.mouse.down(); await page.mouse.move(edge.x + edge.width / 2 + 35, edge.y + edge.height / 2, { steps: 6 });
  await expect(page.getByLabel('Clip duration')).toHaveValue('2'); // live feedback, before release
  await page.mouse.up();
  release();
  await expect(page.locator('.studio-autosave')).toHaveText('Saved');
  const saved = await (await request.get(`${base}/studio/projects/${draft.id}`)).json();
  expect(saved.text_style.color).toBe('#59B5FF');
  expect(saved.clips.map((c: { start_time: number; end_time: number }) => [c.start_time, c.end_time])).toEqual([[0, 2], [2, 3]]);
  expect(count).toBe(2);
  await expect(page.getByLabel('Timeline editor', { exact: true })).toBeFocused();
  await page.unroute(`**/api/studio/projects/${draft.id}/editor`);
  await page.route(`**/api/studio/projects/${draft.id}/editor`, route => route.fulfill({ status: 503, json: { detail: 'Temporary save failure' } }), { times: 1 });
  await page.getByRole('button', { name: 'Green text' }).click();
  await expect(page.getByRole('alert').filter({ hasText: 'Temporary save failure' })).toBeVisible();
  await page.getByRole('button', { name: 'Retry saving' }).click();
  await expect(page.locator('.studio-autosave')).toHaveText('Saved');
  await page.reload();
  await page.getByRole('button', { name: '4. Visuals', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Green text' })).toHaveAttribute('aria-pressed', 'true');
  const editor = page.getByLabel('Timeline editor', { exact: true });
  await editor.focus(); await page.keyboard.press('Space');
  await expect(page.getByTestId('global-audio')).toHaveJSProperty('paused', false);
  await page.keyboard.press('Space');
  await expect(page.getByTestId('global-audio')).toHaveJSProperty('paused', true);
  await page.getByRole('button', { name: 'Add clips', exact: true }).click();
  const tray = page.getByRole('region', { name: 'Insert clips' });
  await expect(tray.locator('video')).toHaveCount(1);
  await tray.locator('video').scrollIntoViewIfNeeded();
  await tray.getByRole('button', { name: `Play Clip ${media.id} preview` }).click();
  await expect.poll(() => tray.locator('video').evaluate((v: HTMLVideoElement) => v.videoWidth)).toBe(160);
  await tray.getByLabel('Find saved footage').fill('generic');
  await page.keyboard.press('Space');
  await expect(page.getByTestId('global-audio')).toHaveJSProperty('paused', true);
  await tray.getByLabel('Find saved footage').fill('');
  const before = saved.clips.map((c: { start_time: number; end_time: number }) => c.end_time - c.start_time);
  await tray.getByRole('button', { name: `Insert clip ${media.id}`, exact: true }).click();
  await expect(page.locator('.studio-autosave')).toHaveText('Saved');
  expect((await (await request.get(`${base}/studio/projects/${draft.id}`)).json()).clips).toHaveLength(1);
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(page.locator('.studio-autosave')).toHaveText('Saved');
  expect((await (await request.get(`${base}/studio/projects/${draft.id}`)).json()).clips.map((c: { start_time: number; end_time: number }) => c.end_time - c.start_time)).toEqual(before);
  await page.getByRole('button', { name: 'Add clips', exact: true }).click();
  const transfer = await page.evaluateHandle(() => new DataTransfer());
  await tray.getByRole('button', { name: `Insert clip ${media.id}`, exact: true }).dispatchEvent('dragstart', { dataTransfer: transfer });
  const destination = page.locator('[data-timeline-index="1"]');
  await destination.dispatchEvent('dragover', { dataTransfer: transfer });
  await destination.dispatchEvent('drop', { dataTransfer: transfer });
  await expect(page.locator('.studio-autosave')).toHaveText('Saved');
  expect((await (await request.get(`${base}/studio/projects/${draft.id}`)).json()).clips.map((c: { start_time: number; end_time: number }) => c.end_time - c.start_time)).toEqual([2, 1]);
  await page.getByRole('button', { name: 'Add clips', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await tray.scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath('visual-insert-mobile.png') });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
